// Builds the two tactical soldier Avatar Packages from the shared source in scripts/lib/soldier/.
//   node scripts/build-soldier-avatars.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['1-kit.js', '2-body.js', '3-anim.js'].map((f) => readFileSync(join(root, 'scripts/lib/soldier', f), 'utf8')).join('\n');

const AVATARS = [
  {
    // mid-tone police blue: readable against both the dark containers and the bright quay
    id: 'swat-operator', version: '2.0.0', name: 'SWAT Operator', style: 'swat', height: 1.762, label: 'POLICE',
    palette: { uniform: 0x3f5f85, pants: 0x385676, mask: 0x4d5f78, skin: 0xb98a6b, vest: 0x24344a, pouch: 0x2a3c55, strap: 0x1f2c3f, belt: 0x1b2535, helmet: 0x2c3e57, pad: 0x1a1d22, lens: 0x5a6672, glove: 0x22262c, gloveHard: 0x15171a, boot: 0x1c1d20, sole: 0x101112, scarf: 0x2a3442, accent: 0xd8dde4 },
    firstPersonArms: { sleeve: '#3f5f85', glove: '#22262c' },
  },
  {
    id: 'masked-raider', version: '2.0.0', name: 'Masked Raider', style: 'raider', height: 1.762,
    palette: { uniform: 0x8c7648, pants: 0x5d6542, mask: 0xa08c66, cap: 0x4a3a2c, skin: 0xa87a5c, vest: 0x3b3a2e, pouch: 0x4a4636, strap: 0x33322a, belt: 0x2b2a22, helmet: 0x3b3a2e, pad: 0x24231f, lens: 0x1c1d1f, glove: 0x6b4a2e, gloveHard: 0x3c2a1b, boot: 0x5a4630, sole: 0x221c15, scarf: 0x8e2f2a, accent: 0x8e2f2a },
    firstPersonArms: { sleeve: '#8c7648', glove: '#6b4a2e' },
  },
];

for (const a of AVATARS) {
  const cfg = JSON.stringify({ id: a.id, version: a.version, name: a.name, style: a.style, height: a.height, label: a.label || null, palette: a.palette, firstPersonArms: a.firstPersonArms });
  const src = `// GENERATED by scripts/build-soldier-avatars.mjs from scripts/lib/soldier/*.js — edit the sources, not this file.
// ${a.name}: procedural skinned tactical avatar (no GLB, no external assets). Avatar protocol 1.1.
(function (global) {
'use strict';
${parts}
registerSoldier(global, ${cfg});
})(window);
`;
  const out = join(root, 'public/avatars', a.id);
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'avatar.js'), src);
  console.log(a.id, (src.length / 1024).toFixed(1) + ' KB');
}
